const MAX_SECONDS = 30;

/** Copies a take, or makes it a small Opus file (long ambiences cut, fading out). */
function put(src, dest, encode) {
  if (!encode) return copyFileSync(src, dest);
  const seconds = Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", src]).toString());
  const fade = seconds > MAX_SECONDS ? ["-t", String(MAX_SECONDS), "-af", `afade=t=out:st=${MAX_SECONDS - 2}:d=2`] : [];
  execFileSync("ffmpeg", ["-v", "error", "-y", "-i", src, ...fade, "-vn", "-c:a", "libopus", "-b:a", "64k", dest]);
}

const from = process.argv[2];
